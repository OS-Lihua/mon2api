import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import ganache from "ganache";
import {
	type Abi,
	type Address,
	createPublicClient,
	createWalletClient,
	custom,
	encodeFunctionData,
	type Hex,
	parseEventLogs,
	zeroAddress,
} from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { foundry } from "viem/chains";
import {
	afterAll,
	afterEach,
	beforeAll,
	beforeEach,
	describe,
	expect,
	it,
} from "vitest";
import { escrowAbi, nativeEscrowAbi } from "../src/lib/abi";
import { NATIVE_TOKEN, toChainAmount } from "../src/shared/settlement-asset";

const budget = toChainAmount(1_000_000, "ETH");
const digest = `0x${"ab".repeat(32)}` as Hex;
async function fixture() {
	const provider = ganache.provider({
		logging: { quiet: true },
		chain: {
			chainId: 31337,
			hardfork: "shanghai",
			vmErrorsOnRPCResponse: true,
		},
		wallet: { deterministic: true, totalAccounts: 4 },
	});
	const transport = custom(provider, { retryCount: 0 });
	const client = createPublicClient({
		chain: foundry,
		transport,
		cacheTime: 0,
		pollingInterval: 10,
	});
	const wallets = Object.values(provider.getInitialAccounts()).map(
		({ secretKey }) =>
			createWalletClient({
				chain: foundry,
				transport,
				account: privateKeyToAccount(secretKey as Hex),
			}),
	);
	const [buyer, owner, seller, nextOwner] = wallets;
	if (!buyer || !owner || !seller || !nextOwner)
		throw new Error("Missing test wallets");
	const artifact = JSON.parse(
		readFileSync("contracts/artifacts/NativeUsageEscrow.json", "utf8"),
	) as { abi: Abi; bytecode: Hex };
	const deployment = await client.waitForTransactionReceipt({
		hash: await buyer.deployContract({
			...artifact,
			args: [owner.account.address, 500],
		}),
	});
	const escrow = deployment.contractAddress;
	if (!escrow) throw new Error("Missing native escrow");
	// Generated by the same local compiler as the escrow artifact above.
	const walletArtifact = JSON.parse(
		readFileSync("contracts/artifacts/NativeWithdrawalWallet.json", "utf8"),
	) as { abi: Abi; bytecode: Hex };
	const walletDeployment = await client.waitForTransactionReceipt({
		hash: await buyer.deployContract(walletArtifact),
	});
	const contractWallet = walletDeployment.contractAddress;
	if (!contractWallet) throw new Error("Missing contract wallet");
	const executeWallet = (data: Hex, value = 0n) =>
		buyer.writeContract({
			address: contractWallet,
			abi: walletArtifact.abi,
			functionName: "execute",
			args: [escrow, data],
			value,
		});
	const id =
		`0x${buyer.account.address.slice(2).toLowerCase()}${"01".repeat(12)}` as Hex;
	const open = async (
		value = budget,
		amount = budget,
		sessionId = id,
		resourceProvider = seller.account.address,
	) => {
		const block = await client.getBlock();
		return buyer.writeContract({
			address: escrow,
			abi: nativeEscrowAbi,
			functionName: "openSession",
			args: [
				sessionId,
				resourceProvider,
				digest,
				amount,
				block.timestamp + 300n,
			],
			value,
		});
	};
	const settle = (amount: bigint, nonce: bigint) =>
		owner.writeContract({
			address: escrow,
			abi: escrowAbi,
			functionName: "settle",
			args: [id, amount, nonce, digest],
		});
	const claimable = (owner: Address) =>
		client.readContract({
			address: escrow,
			abi: escrowAbi,
			functionName: "claimable",
			args: [owner],
		});
	const close = (sessionId = id) =>
		owner.writeContract({
			address: escrow,
			abi: escrowAbi,
			functionName: "closeSession",
			args: [sessionId],
		});
	return {
		provider,
		client,
		buyer,
		owner,
		seller,
		nextOwner,
		escrow,
		contractWallet,
		walletAbi: walletArtifact.abi,
		executeWallet,
		id,
		open,
		settle,
		claimable,
		close,
	};
}

describe("native token escrow on an isolated EVM", () => {
	let f: Awaited<ReturnType<typeof fixture>>;
	let snapshot: string;
	beforeAll(async () => {
		execFileSync(process.execPath, ["scripts/compile.mjs", "--test-tokens"]);
		f = await fixture();
	}, 30_000);
	beforeEach(async () => {
		snapshot = await f.provider.request({ method: "evm_snapshot", params: [] });
	});
	afterEach(async () => {
		await f.provider.request({ method: "evm_revert", params: [snapshot] });
	});
	afterAll(async () => {
		await f?.provider.disconnect();
	});

	it("requires an exact native deposit and a consumer-owned ID", async () => {
		expect(
			await f.client.readContract({
				address: f.escrow,
				abi: escrowAbi,
				functionName: "token",
			}),
		).toBe(NATIVE_TOKEN);
		await expect(f.open(0n)).rejects.toThrow("invalid native deposit");
		await expect(f.open(budget + 1n)).rejects.toThrow("invalid native deposit");
		await expect(f.open(budget + 1n, budget + 1n)).rejects.toThrow(
			"invalid native deposit",
		);
		await expect(f.open(budget, budget, digest)).rejects.toThrow(
			"session owner mismatch",
		);
		await f.open();
		expect(await f.client.getBalance({ address: f.escrow })).toBe(budget);
	});

	it("conserves deposited native asset through fee allocation, refund and all withdrawals", async () => {
		await f.open();
		const spent = toChainAmount(123_457, "ETH");
		await f.settle(spent, 0n);
		await f.close();
		const fee = (spent * 500n) / 10_000n;
		expect(await f.claimable(f.seller.account.address)).toBe(spent - fee);
		expect(await f.claimable(f.owner.account.address)).toBe(fee);
		expect(await f.claimable(f.buyer.account.address)).toBe(budget - spent);
		for (const wallet of [f.buyer, f.seller, f.owner]) {
			const before = await f.client.getBalance({
				address: wallet.account.address,
			});
			const amount = await f.claimable(wallet.account.address);
			const receipt = await f.client.waitForTransactionReceipt({
				hash: await wallet.writeContract({
					address: f.escrow,
					abi: escrowAbi,
					functionName: "withdraw",
				}),
			});
			expect(
				await f.client.getBalance({ address: wallet.account.address }),
			).toBe(before + amount - receipt.gasUsed * receipt.effectiveGasPrice);
			expect(await f.claimable(wallet.account.address)).toBe(0n);
			await expect(
				wallet.writeContract({
					address: f.escrow,
					abi: escrowAbi,
					functionName: "withdraw",
				}),
			).rejects.toThrow("nothing to withdraw");
		}
		expect(await f.client.getBalance({ address: f.escrow })).toBe(0n);
	});

	it("lets a contract wallet that rejects native transfers send its refund to another recipient", async () => {
		const id = `0x${f.contractWallet.slice(2)}${"02".repeat(12)}` as Hex;
		const block = await f.client.getBlock();
		await f.executeWallet(
			encodeFunctionData({
				abi: nativeEscrowAbi,
				functionName: "openSession",
				args: [
					id,
					f.seller.account.address,
					digest,
					budget,
					block.timestamp + 300n,
				],
			}),
			budget,
		);
		await f.close(id);
		await expect(
			f.executeWallet(
				encodeFunctionData({ abi: escrowAbi, functionName: "withdraw" }),
			),
		).rejects.toThrow("Native transfer failed");
		expect(await f.claimable(f.contractWallet)).toBe(budget);
		const before = await f.client.getBalance({
			address: f.seller.account.address,
		});
		const receipt = await f.client.waitForTransactionReceipt({
			hash: await f.executeWallet(
				encodeFunctionData({
					abi: nativeEscrowAbi,
					functionName: "withdrawTo",
					args: [f.seller.account.address],
				}),
			),
		});
		expect(
			await f.client.getBalance({ address: f.seller.account.address }),
		).toBe(before + budget);
		expect(await f.claimable(f.contractWallet)).toBe(0n);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(0n);
		const events = parseEventLogs({
			abi: escrowAbi,
			eventName: "Withdrawn",
			logs: receipt.logs,
		});
		expect(events[0]?.args).toEqual({
			recipient: f.seller.account.address,
			amount: budget,
		});
	});

	it("lets a provider contract wallet redirect its earnings without spending other balances", async () => {
		await f.open(budget, budget, f.id, f.contractWallet);
		const spent = budget / 2n;
		await f.settle(spent, 0n);
		await f.close();
		const earnings = await f.claimable(f.contractWallet);
		const fee = await f.claimable(f.owner.account.address);
		const before = await f.client.getBalance({
			address: f.seller.account.address,
		});
		await f.executeWallet(
			encodeFunctionData({
				abi: nativeEscrowAbi,
				functionName: "withdrawTo",
				args: [f.seller.account.address],
			}),
		);
		expect(
			await f.client.getBalance({ address: f.seller.account.address }),
		).toBe(before + earnings);
		expect(await f.claimable(f.contractWallet)).toBe(0n);
		expect(await f.claimable(f.buyer.account.address)).toBe(budget - spent);
		expect(await f.claimable(f.owner.account.address)).toBe(fee);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(
			budget - earnings,
		);
	});

	it("rejects a zero recipient and cannot use a recipient address to withdraw someone else's credit", async () => {
		await f.open();
		await f.close();
		await expect(
			f.buyer.writeContract({
				address: f.escrow,
				abi: nativeEscrowAbi,
				functionName: "withdrawTo",
				args: [zeroAddress],
			}),
		).rejects.toThrow("zero recipient");
		await expect(
			f.seller.writeContract({
				address: f.escrow,
				abi: nativeEscrowAbi,
				functionName: "withdrawTo",
				args: [f.buyer.account.address],
			}),
		).rejects.toThrow("nothing to withdraw");
		expect(await f.claimable(f.buyer.account.address)).toBe(budget);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(budget);
	});

	it("retains credit after a rejected payout and allows exactly one successful retry", async () => {
		await f.open();
		await f.close();
		await expect(
			f.buyer.writeContract({
				address: f.escrow,
				abi: nativeEscrowAbi,
				functionName: "withdrawTo",
				args: [f.contractWallet],
			}),
		).rejects.toThrow("Native transfer failed");
		expect(await f.claimable(f.buyer.account.address)).toBe(budget);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(budget);
		const before = await f.client.getBalance({
			address: f.owner.account.address,
		});
		await f.buyer.writeContract({
			address: f.escrow,
			abi: nativeEscrowAbi,
			functionName: "withdrawTo",
			args: [f.owner.account.address],
		});
		expect(
			await f.client.getBalance({ address: f.owner.account.address }),
		).toBe(before + budget);
		expect(await f.claimable(f.buyer.account.address)).toBe(0n);
		await expect(
			f.buyer.writeContract({
				address: f.escrow,
				abi: nativeEscrowAbi,
				functionName: "withdrawTo",
				args: [f.seller.account.address],
			}),
		).rejects.toThrow("nothing to withdraw");
	});

	it("blocks reentry through both withdrawal methods even when the recipient has its own credit", async () => {
		await f.open(budget, budget, f.id, f.contractWallet);
		await f.settle(budget / 2n, 0n);
		await f.close();
		const earnings = await f.claimable(f.contractWallet);
		const refund = await f.claimable(f.buyer.account.address);
		await f.buyer.writeContract({
			address: f.contractWallet,
			abi: f.walletAbi,
			functionName: "enableReentry",
			args: [f.escrow],
		});
		await f.buyer.writeContract({
			address: f.escrow,
			abi: nativeEscrowAbi,
			functionName: "withdrawTo",
			args: [f.contractWallet],
		});
		const read = (functionName: "attempted" | "reentered" | "received") =>
			f.client.readContract({
				address: f.contractWallet,
				abi: f.walletAbi,
				functionName,
			});
		expect(await read("attempted")).toBe(true);
		expect(await read("reentered")).toBe(false);
		expect(await read("received")).toBe(refund);
		expect(await f.claimable(f.buyer.account.address)).toBe(0n);
		expect(await f.claimable(f.contractWallet)).toBe(earnings);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(
			budget - refund,
		);
		// The recipient's credit stays available for its own later transaction.
		await f.executeWallet(
			encodeFunctionData({
				abi: escrowAbi,
				functionName: "withdraw",
			}),
		);
		expect(await read("received")).toBe(refund + earnings);
		expect(await f.claimable(f.contractWallet)).toBe(0n);
		expect(await f.client.getBalance({ address: f.escrow })).toBe(
			await f.claimable(f.owner.account.address),
		);
	});

	it("rejects overcharging, replay, unauthorized settlement and sub-billing precision", async () => {
		await f.open();
		await expect(
			f.settle(budget + toChainAmount(1, "ETH"), 0n),
		).rejects.toThrow("invalid amount");
		await expect(f.settle(1n, 0n)).rejects.toThrow("invalid billing precision");
		await expect(
			f.seller.writeContract({
				address: f.escrow,
				abi: escrowAbi,
				functionName: "settle",
				args: [f.id, toChainAmount(1, "ETH"), 0n, digest],
			}),
		).rejects.toThrow("revert");
		await f.settle(toChainAmount(1, "ETH"), 0n);
		await expect(f.settle(toChainAmount(2, "ETH"), 0n)).rejects.toThrow(
			"invalid receipt",
		);
	});

	it("lets the consumer recover unused native asset when the meter is unavailable", async () => {
		await f.open();
		await f.buyer.writeContract({
			address: f.escrow,
			abi: escrowAbi,
			functionName: "requestClose",
			args: [f.id],
		});
		await expect(
			f.buyer.writeContract({
				address: f.escrow,
				abi: escrowAbi,
				functionName: "closeSession",
				args: [f.id],
			}),
		).rejects.toThrow("await settlement window");
		await f.provider.request({ method: "evm_increaseTime", params: [121] });
		await f.provider.request({ method: "evm_mine", params: [] });
		await f.buyer.writeContract({
			address: f.escrow,
			abi: escrowAbi,
			functionName: "closeSession",
			args: [f.id],
		});
		expect(await f.claimable(f.buyer.account.address)).toBe(budget);
		await expect(f.settle(toChainAmount(1, "ETH"), 0n)).rejects.toThrow(
			"inactive session",
		);
	});
});
