import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import ganache from "ganache";
import {
	type Abi,
	type Address,
	createPublicClient,
	createWalletClient,
	custom,
	type Hex,
	isHex,
} from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { foundry } from "viem/chains";
import {
	afterAll,
	afterEach,
	beforeAll,
	beforeEach,
	describe,
	expect,
	it,
} from "vitest";
import { escrowAbi, nativeEscrowAbi, tokenAbi } from "~/lib/abi";
import { prepaidAbi } from "~/lib/prepaid-abi";

beforeAll(() => {
	execFileSync(process.execPath, ["scripts/compile.mjs", "--test-tokens"]);
}, 30_000);
async function fixture(native: boolean, decimals: number) {
	const provider = ganache.provider({
		logging: { quiet: true },
		chain: {
			chainId: 31337,
			hardfork: "shanghai",
			vmErrorsOnRPCResponse: true,
		},
		wallet: { deterministic: true, totalAccounts: 4 },
	});
	const transport = custom(provider, { retryCount: 0 });
	const client = createPublicClient({
		chain: foundry,
		transport,
		cacheTime: 0,
		pollingInterval: 10,
	});
	const wallets = Object.values(provider.getInitialAccounts()).map(
		({ secretKey }) => {
			if (!isHex(secretKey)) throw new Error("Invalid isolated test key.");
			return createWalletClient({
				chain: foundry,
				transport,
				account: privateKeyToAccount(secretKey),
			});
		},
	);
	const [buyer, owner, seller, outsider] = wallets;
	if (!buyer || !owner || !seller || !outsider)
		throw new Error("Missing isolated test wallets.");
	// Trusted artifacts are generated by this repository's Solidity compiler above.
	const artifact = (name: string) =>
		JSON.parse(readFileSync(`contracts/artifacts/${name}.json`, "utf8")) as {
			abi: Abi;
			bytecode: Hex;
		};
	let token: Address | null = null;
	if (!native) {
		const deployed = await client.waitForTransactionReceipt({
			hash: await buyer.deployContract({
				...artifact("SettlementTestToken"),
				args: [decimals],
			}),
		});
		token = deployed.contractAddress ?? null;
		if (!token) throw new Error("Missing test token.");
	}
	const receipt = await client.waitForTransactionReceipt({
		hash: await buyer.deployContract({
			...artifact(native ? "NativeUsageEscrow" : "UsageEscrow"),
			args: native
				? [owner.account.address, 500]
				: [token, owner.account.address, 500],
		}),
	});
	const escrow = receipt.contractAddress;
	if (!escrow) throw new Error("Missing test escrow.");
	const unit = 10n ** BigInt(decimals - 6);
	if (token) {
		await buyer.writeContract({
			address: token,
			abi: tokenAbi,
			functionName: "mint",
			args: [buyer.account.address, 10_000_000n * unit],
		});
		await buyer.writeContract({
			address: token,
			abi: tokenAbi,
			functionName: "approve",
			args: [escrow, 10_000_000n * unit],
		});
	}
	const id =
		`0x${buyer.account.address.slice(2).toLowerCase()}${"12".repeat(12)}` as Hex;
	const digest = `0x${"ab".repeat(32)}` as Hex;
	const deposit = (micro = 2_000_000n) =>
		buyer.writeContract({
			address: escrow,
			abi: prepaidAbi,
			functionName: "depositPrepaid",
			args: [micro * unit],
			value: native ? micro * unit : 0n,
		});
	const balance = () =>
		client.readContract({
			address: escrow,
			abi: prepaidAbi,
			functionName: "prepaidBalance",
			args: [buyer.account.address],
		});
	const reserve = async (signer = owner) =>
		signer.writeContract({
			address: escrow,
			abi: prepaidAbi,
			functionName: "reservePrepaidSession",
			args: [
				id,
				buyer.account.address,
				seller.account.address,
				digest,
				1_000_000n * unit,
				(await client.getBlock()).timestamp + 300n,
			],
		});
	const settle = (retail = 400_000n, wholesale = 200_000n, nonce = 0n) =>
		owner.writeContract({
			address: escrow,
			abi: prepaidAbi,
			functionName: "settlePrepaid",
			args: [id, retail * unit, wholesale * unit, nonce, digest],
		});
	const claimable = (address: Address) =>
		client.readContract({
			address: escrow,
			abi: escrowAbi,
			functionName: "claimable",
			args: [address],
		});
	const close = () =>
		owner.writeContract({
			address: escrow,
			abi: escrowAbi,
			functionName: "closeSession",
			args: [id],
		});
	return {
		provider,
		client,
		buyer,
		owner,
		seller,
		outsider,
		escrow,
		unit,
		id,
		digest,
		deposit,
		balance,
		reserve,
		settle,
		claimable,
		close,
	};
}

describe.each([
	{ name: "native", native: true, decimals: 18 },
	{ name: "ERC20/6", native: false, decimals: 6 },
	{ name: "ERC20/18", native: false, decimals: 18 },
])("prepaid account $name", ({ native, decimals }) => {
	let f: Awaited<ReturnType<typeof fixture>>;
	let snapshot: string;
	beforeAll(async () => {
		f = await fixture(native, decimals);
	}, 30_000);
	beforeEach(async () => {
		snapshot = await f.provider.request({ method: "evm_snapshot", params: [] });
	});
	afterEach(async () => {
		await f.provider.request({ method: "evm_revert", params: [snapshot] });
	});
	afterAll(async () => {
		await f?.provider.disconnect();
	});
	it("conserves retail charges, supplier income, margin, refund and withdrawal", async () => {
		await f.deposit();
		await f.reserve();
		expect(await f.balance()).toBe(1_000_000n * f.unit);
		await f.settle();
		expect(await f.claimable(f.seller.account.address)).toBe(190_000n * f.unit);
		expect(await f.claimable(f.owner.account.address)).toBe(210_000n * f.unit);
		await f.close();
		expect(await f.balance()).toBe(1_600_000n * f.unit);
		expect(await f.claimable(f.buyer.account.address)).toBe(0n);
		await f.buyer.writeContract({
			address: f.escrow,
			abi: prepaidAbi,
			functionName: "withdrawPrepaid",
			args: [600_000n * f.unit],
		});
		expect(await f.balance()).toBe(1_000_000n * f.unit);
	});
	it("holds reserved funds and rejects overspending or replay", async () => {
		await f.deposit();
		await f.reserve();
		await expect(
			f.buyer.writeContract({
				address: f.escrow,
				abi: prepaidAbi,
				functionName: "withdrawPrepaid",
				args: [1_000_001n * f.unit],
			}),
		).rejects.toThrow("insufficient prepaid balance");
		await expect(f.settle(1_000_001n)).rejects.toThrow("invalid amount");
		await expect(f.settle(400_000n, 400_001n)).rejects.toThrow(
			"invalid provider amount",
		);
		await f.settle();
		await expect(f.settle()).rejects.toThrow("invalid receipt");
	});
	it("rejects unauthorised allocation and mixed settlement paths", async () => {
		await f.deposit();
		await expect(f.reserve(f.outsider)).rejects.toThrow();
		await f.reserve();
		await expect(f.reserve()).rejects.toThrow("session exists");
		await expect(
			f.owner.writeContract({
				address: f.escrow,
				abi: escrowAbi,
				functionName: "settle",
				args: [f.id, 100_000n * f.unit, 0n, f.digest],
			}),
		).rejects.toThrow("use prepaid settlement");
	});
	it("preserves wallet-funded sessions and their claimable refunds", async () => {
		await f.deposit();
		const args = [
			f.id,
			f.seller.account.address,
			f.digest,
			1_000_000n * f.unit,
			(await f.client.getBlock()).timestamp + 300n,
		] as const;
		if (native)
			await f.buyer.writeContract({
				address: f.escrow,
				abi: nativeEscrowAbi,
				functionName: "openSession",
				args,
				value: 1_000_000n * f.unit,
			});
		else
			await f.buyer.writeContract({
				address: f.escrow,
				abi: escrowAbi,
				functionName: "openSession",
				args,
			});
		await f.owner.writeContract({
			address: f.escrow,
			abi: escrowAbi,
			functionName: "settle",
			args: [f.id, 400_000n * f.unit, 0n, f.digest],
		});
		await f.close();
		expect(await f.balance()).toBe(2_000_000n * f.unit);
		expect(await f.claimable(f.buyer.account.address)).toBe(600_000n * f.unit);
		expect(await f.claimable(f.seller.account.address)).toBe(380_000n * f.unit);
	});
	it("permits free-balance withdrawal and expired refunds while paused", async () => {
		await f.deposit();
		await f.reserve();
		await f.owner.writeContract({
			address: f.escrow,
			abi: escrowAbi,
			functionName: "pause",
		});
		await expect(f.deposit()).rejects.toThrow();
		await expect(f.settle()).rejects.toThrow();
		await f.buyer.writeContract({
			address: f.escrow,
			abi: prepaidAbi,
			functionName: "withdrawPrepaid",
			args: [1_000_000n * f.unit],
		});
		expect(await f.balance()).toBe(0n);
		await f.provider.request({ method: "evm_increaseTime", params: [421] });
		await f.provider.request({ method: "evm_mine", params: [] });
		await f.outsider.writeContract({
			address: f.escrow,
			abi: escrowAbi,
			functionName: "closeSession",
			args: [f.id],
		});
		expect(await f.balance()).toBe(1_000_000n * f.unit);
	});
	if (decimals > 6)
		it("keeps deposits and withdrawals at whole micro-unit precision", async () => {
			await expect(
				f.buyer.writeContract({
					address: f.escrow,
					abi: prepaidAbi,
					functionName: "depositPrepaid",
					args: [1n],
					value: native ? 1n : 0n,
				}),
			).rejects.toThrow();
			expect(await f.balance()).toBe(0n);
			await f.deposit();
			await expect(
				f.buyer.writeContract({
					address: f.escrow,
					abi: prepaidAbi,
					functionName: "withdrawPrepaid",
					args: [1n],
				}),
			).rejects.toThrow("invalid billing precision");
			expect(await f.balance()).toBe(2_000_000n * f.unit);
		});
});
